//! Writes an emitted crate to disk.
//!
//! Everything here is filesystem policy: the crate layout, the stale-root cleanup
//! and the write-only-when-changed rule Cargo's incremental reuse depends on.

use std::{fs, path::Path};

use smelt_mir::Mir;

use crate::crate_builder::{FreeFunctionHome, emit_root};
use crate::gates::assert_runtime_symbols_defined;
use crate::module_map::emit_mapped_sources;
use crate::{CrateKind, EmitOptions, deps};

/// Emits a complete Rust crate from the given MIR.
///
/// Creates the crate structure with Cargo.toml and the configured crate root.
pub fn emit_crate(
    mir: &Mir,
    output_path: impl AsRef<Path>,
    options: &EmitOptions,
) -> Result<(), Box<dyn std::error::Error>> {
    let output_dir = output_path.as_ref();
    let src_dir = output_dir.join("src");
    fs::create_dir_all(&src_dir)?;
    let allocator = options.effective_allocator();
    let root = emit_root(mir, allocator, |_function, _context| FreeFunctionHome::Root)?;
    let source = root.source();
    assert_runtime_symbols_defined([source.as_str()])?;
    write_if_changed(
        output_dir.join("Cargo.toml"),
        &deps::cargo_toml(&options.crate_name, &root.dependencies, allocator, options),
    )?;
    write_crate_root(&src_dir, options.crate_kind, &source)?;
    remove_stale_modules(&src_dir, options.crate_kind, &[])?;
    Ok(())
}

/// Emits a complete Rust crate while preserving the source module layout.
///
/// Shared generated runtime/types stay in the configured crate root. Non-entry
/// module-level functions are moved into source-shaped Rust modules and
/// re-exported from the crate root so existing flat-name call emission
/// continues to resolve.
pub fn emit_crate_with_modules(
    mir: &Mir,
    krate: &smelt_hir::Crate,
    modules: &[(String, smelt_hir::ModuleId)],
    output_path: impl AsRef<Path>,
    options: &EmitOptions,
) -> Result<(), Box<dyn std::error::Error>> {
    emit_crate_with_modules_reporting(mir, krate, modules, output_path, options).map(|_| ())
}

/// [`emit_crate_with_modules`], also returning the backend's erasures.
///
/// These are the erasures decided while rendering types (erased generics and
/// unions, unresolved classes, `never`). See `emitter::backend_erasure` for the
/// span each record carries. The records are unsorted and may repeat;
/// normalize them with [`smelt_hir::normalize_erasures`].
pub fn emit_crate_with_modules_reporting(
    mir: &Mir,
    krate: &smelt_hir::Crate,
    modules: &[(String, smelt_hir::ModuleId)],
    output_path: impl AsRef<Path>,
    options: &EmitOptions,
) -> Result<Vec<smelt_hir::ErasureRecord>, Box<dyn std::error::Error>> {
    let output_dir = output_path.as_ref();
    let src_dir = output_dir.join("src");
    fs::create_dir_all(&src_dir)?;
    let allocator = options.effective_allocator();
    let mapped = emit_mapped_sources(mir, krate, modules, allocator)?;
    assert_runtime_symbols_defined(
        std::iter::once(mapped.root.as_str())
            .chain(mapped.modules.iter().map(|module| module.source.as_str())),
    )?;
    write_if_changed(
        output_dir.join("Cargo.toml"),
        &deps::cargo_toml(
            &options.crate_name,
            &mapped.dependencies,
            allocator,
            options,
        ),
    )?;
    write_crate_root(&src_dir, options.crate_kind, &mapped.root)?;
    let mut written = Vec::with_capacity(mapped.modules.len());
    for module in mapped.modules {
        let file_name = format!("{}.rs", module.name);
        write_if_changed(src_dir.join(&file_name), &module.source)?;
        written.push(file_name);
    }
    remove_stale_modules(&src_dir, options.crate_kind, &written)?;
    Ok(mapped.erasures)
}

/// The first line of every file the emitter writes, which marks a file in
/// `src/` as Smelt's to replace or remove.
const GENERATED_HEADER: &str = "// @generated by smelt. Do not edit by hand.";

/// Removes the generated module files of an earlier build that this build no
/// longer writes.
///
/// A source module that was renamed or deleted leaves its old `.rs` beside the
/// new ones, undeclared but still counted by the SmeltUnknown and typedness
/// reports, which scan `src/`. Only a file that starts with Smelt's generated
/// header is removed: a hand-written file in the output directory is never
/// touched. `written` holds the file names this build wrote; the crate root is
/// kept.
fn remove_stale_modules(
    src_dir: &Path,
    crate_kind: CrateKind,
    written: &[String],
) -> Result<(), Box<dyn std::error::Error>> {
    for entry in fs::read_dir(src_dir)? {
        let path = entry?.path();
        let Some(file_name) = path.file_name().and_then(|name| name.to_str()) else {
            continue;
        };
        if !path.is_file()
            || path.extension().is_none_or(|extension| extension != "rs")
            || file_name == crate_kind.root_file_name()
            || written.iter().any(|kept| kept == file_name)
        {
            continue;
        }
        if fs::read_to_string(&path).is_ok_and(|text| text.starts_with(GENERATED_HEADER)) {
            fs::remove_file(&path)?;
        }
    }
    Ok(())
}

/// Writes the configured crate root and removes the stale opposite root.
///
/// Cargo infers program and library targets from `src/main.rs` and `src/lib.rs`.
/// Removing the other generated root keeps manifest kind changes from silently
/// producing both targets in the same output directory.
fn write_crate_root(
    src_dir: &Path,
    crate_kind: CrateKind,
    contents: &str,
) -> Result<(), Box<dyn std::error::Error>> {
    write_if_changed(src_dir.join(crate_kind.root_file_name()), contents)?;
    let stale_root = src_dir.join(crate_kind.stale_root_file_name());
    if stale_root.exists() {
        fs::remove_file(stale_root)?;
    }
    Ok(())
}

/// Writes generated text only when the destination bytes actually change.
///
/// Cargo uses file mtimes as part of its freshness checks. Rewriting every
/// generated Rust module on each Smelt build forces Cargo to recompile modules
/// whose source is byte-for-byte identical, which dominates large projects such
/// as Remeda. Keeping identical files untouched preserves incremental build
/// artifacts without changing Smelt's lowering or codegen semantics.
fn write_if_changed(
    path: impl AsRef<Path>,
    contents: &str,
) -> Result<(), Box<dyn std::error::Error>> {
    let destination = path.as_ref();
    if fs::read_to_string(destination).is_ok_and(|existing| existing == contents) {
        return Ok(());
    }
    fs::write(destination, contents)?;
    Ok(())
}

#[cfg(test)]
#[expect(clippy::expect_used, reason = "a test fails fast on fixture setup")]
mod tests {
    use super::{GENERATED_HEADER, remove_stale_modules};
    use crate::CrateKind;

    /// The crate root carries the header stale-module removal recognises, so
    /// a root left by an earlier build of the other crate kind is Smelt's.
    #[test]
    fn the_crate_root_starts_with_the_generated_header() {
        assert!(crate::crate_builder::CRATE_HEADER.starts_with(GENERATED_HEADER));
    }

    /// A generated module this build did not write is removed; the root, the
    /// modules it wrote and every file without the header are kept.
    #[test]
    fn only_unwritten_generated_modules_are_removed() {
        let dir = tempfile::tempdir().expect("temporary directory");
        let src = dir.path();
        let generated = format!("{GENERATED_HEADER}\nfn f() {{}}\n");
        for (name, text) in [
            ("main.rs", generated.as_str()),
            ("kept.rs", generated.as_str()),
            ("stale.rs", generated.as_str()),
            ("mine.rs", "// hand-written\n"),
            ("notes.txt", generated.as_str()),
        ] {
            std::fs::write(src.join(name), text).expect("write fixture");
        }
        remove_stale_modules(src, CrateKind::Program, &["kept.rs".to_owned()]).expect("cleanup");
        for kept in ["main.rs", "kept.rs", "mine.rs", "notes.txt"] {
            assert!(src.join(kept).exists(), "{kept} must be kept");
        }
        assert!(
            !src.join("stale.rs").exists(),
            "a stale generated module must be removed"
        );
    }
}
