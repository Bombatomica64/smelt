//! The order runtime items are written into a generated crate.
//!
//! Every item lives in the family file that reads best, but a generated crate is
//! one flat module whose text is compared byte for byte, so emission order is a
//! fact of its own. Each entry is emitted when its own `when` expression holds;
//! see [`crate::source`] for the marker language.

/// One step of emitting the runtime.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub enum Entry {
    /// A marked item, by name.
    Item(&'static str),
    /// A blank line, written when its expression holds.
    ///
    /// Item text carries its own trailing blank lines. These are the blanks that
    /// separate items even when the item before them is not emitted.
    Blank(&'static str),
}

