#!/usr/bin/env python3
"""Regenerate `crates/smelt-ts-types/src/node_types.rs` from the vendored packages.

The TypeScript checker Smelt embeds gets Node's declarations from a pinned
copy of `@types/node` (and its one dependency, `undici-types`) under
`crates/smelt-ts-types/vendor/node_modules`. To update them, replace that
directory with the unpacked packages (`npm pack @types/node@<v> undici-types@<v>`)
and run this script; it lists every `.d.ts` and `package.json` there as an
`include_str!` table.
"""

import pathlib

CRATE = pathlib.Path(__file__).resolve().parent.parent / "crates" / "smelt-ts-types"
VENDOR = CRATE / "vendor"


def main() -> None:
    files = sorted(
        path
        for path in VENDOR.rglob("*")
        if path.is_file() and (path.name.endswith(".d.ts") or path.name == "package.json")
    )
    lines = [
        "//! The vendored Node type declarations, as `(program path, text)` pairs.",
        "//!",
        "//! Generated by `scripts/vendor_node_types.py`; do not edit by hand. The",
        "//! packages and their versions are under `vendor/node_modules`.",
        "",
        "/// Every vendored declaration file, keyed by its path under `node_modules/`'s parent.",
        "pub(crate) const NODE_TYPE_FILES: &[(&str, &str)] = &[",
    ]
    for path in files:
        relative = path.relative_to(VENDOR).as_posix()
        lines.append(f'    ("{relative}", include_str!("../vendor/{relative}")),')
    lines.append("];")
    (CRATE / "src" / "node_types.rs").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
